import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";

/**
 * Smoke coverage for the analytics dashboard export flow.
 *
 * `/dashboard/*` is protected by `mux_auth_session` (see src/middleware.ts)
 * so every test signs in through the real login flow first. With
 * `NEXT_PUBLIC_API_URL` unset (the playwright dev-server env), the analytics
 * page falls back to mock data: `useAnalyticsMetrics` loads the mock
 * metrics/charts, and `useAnalyticsTransactions` loads the mock export rows.
 *
 * What this spec guards: the CSV / JSON export buttons are rendered and, when
 * the page has real (mock-backed) transaction rows, clicking them triggers a
 * genuine file download whose contents are non-empty and internally
 * consistent between the two formats. In a production build with no backend
 * the export would surface an error instead of silently succeeding — see
 * `src/docs/Analytics_Data_Sources.md`.
 */
async function signIn(page: import("@playwright/test").Page) {
	await page.goto("/login");
	await page.getByLabel("Email address").fill("dev@muxprotocol.com");
	await page.getByLabel("Password").fill("password123");
	await page.getByTestId("login-submit").click();
	await page.waitForURL("**/dashboard**");
}

/**
 * Minimal CSV line splitter that tolerates quoted fields (including embedded
 * commas and escaped double quotes). The analytics export is generated by the
 * page itself, so a small tolerant parser is enough here.
 */
function splitCsvLine(line: string): string[] {
	const fields: string[] = [];
	let current = "";
	let inQuotes = false;

	for (let i = 0; i < line.length; i++) {
		const char = line[i];
		if (inQuotes) {
			if (char === '"') {
				if (line[i + 1] === '"') {
					current += '"';
					i++;
				} else {
					inQuotes = false;
				}
			} else {
				current += char;
			}
		} else if (char === '"') {
			inQuotes = true;
		} else if (char === ",") {
			fields.push(current);
			current = "";
		} else {
			current += char;
		}
	}
	fields.push(current);
	return fields;
}

async function readDownloadedText(
	download: import("@playwright/test").Download,
): Promise<string> {
	const filePath = await download.path();
	expect(filePath).toBeTruthy();
	return readFile(filePath as string, "utf8");
}

async function downloadCsv(
	page: import("@playwright/test").Page,
): Promise<{ header: string[]; rows: string[][] }> {
	const exportButton = page.getByRole("button", { name: /export.*csv/i });
	await expect(exportButton).toBeEnabled();

	const downloadPromise = page.waitForEvent("download");
	await exportButton.click();
	const download = await downloadPromise;

	expect(download.suggestedFilename()).toMatch(/^analytics-.*\.csv$/);

	const contents = await readDownloadedText(download);
	const lines = contents
		.split(/\r?\n/)
		.map((line) => line.trim())
		.filter((line) => line.length > 0);

	expect(lines.length).toBeGreaterThanOrEqual(2);

	const [headerLine, ...dataLines] = lines;
	return {
		header: splitCsvLine(headerLine),
		rows: dataLines.map(splitCsvLine),
	};
}

async function downloadJson(
	page: import("@playwright/test").Page,
): Promise<Record<string, unknown>[]> {
	const exportButton = page.getByRole("button", { name: /export.*json/i });
	await expect(exportButton).toBeEnabled();

	const downloadPromise = page.waitForEvent("download");
	await exportButton.click();
	const download = await downloadPromise;

	expect(download.suggestedFilename()).toMatch(/^analytics-.*\.json$/);

	const contents = await readDownloadedText(download);
	const parsed = JSON.parse(contents);
	expect(Array.isArray(parsed)).toBe(true);
	expect(parsed.length).toBeGreaterThanOrEqual(1);
	return parsed as Record<string, unknown>[];
}

/**
 * Downloads both exports and returns their parsed rows so a test can assert
 * the two formats describe the same underlying data.
 */
async function downloadExports(page: import("@playwright/test").Page): Promise<{
	csvHeader: string[];
	csvRows: string[][];
	jsonRows: Record<string, unknown>[];
}> {
	const csv = await downloadCsv(page);
	const jsonRows = await downloadJson(page);
	return { csvHeader: csv.header, csvRows: csv.rows, jsonRows };
}

test.describe("Analytics dashboard export smoke", () => {
	test("renders the analytics page with export controls once signed in", async ({
		page,
	}) => {
		await signIn(page);
		await page.goto("/dashboard/analytics");

		// The page loads mock-backed analytics data in this environment.
		await expect(
			page.getByRole("button", { name: /export.*csv/i }),
		).toBeEnabled();
		await expect(
			page.getByRole("button", { name: /export.*json/i }),
		).toBeEnabled();
	});

	test("downloads the transaction list as CSV", async ({ page }) => {
		await signIn(page);
		await page.goto("/dashboard/analytics");

		const { header, rows } = await downloadCsv(page);

		// Header row plus at least one data row.
		expect(header.length).toBeGreaterThanOrEqual(1);
		expect(rows.length).toBeGreaterThanOrEqual(1);
	});

	test("downloads the transaction list as JSON", async ({ page }) => {
		await signIn(page);
		await page.goto("/dashboard/analytics");

		const parsed = await downloadJson(page);

		expect(Array.isArray(parsed)).toBe(true);
		expect(parsed.length).toBeGreaterThanOrEqual(1);
	});

	test("CSV and JSON exports describe the same rows", async ({ page }) => {
		await signIn(page);
		await page.goto("/dashboard/analytics");

		const { csvHeader, csvRows, jsonRows } = await downloadExports(page);

		expect(csvRows.length).toBeGreaterThanOrEqual(1);
		expect(jsonRows.length).toBeGreaterThanOrEqual(1);
		expect(csvRows.length).toBe(jsonRows.length);

		// Both exports should carry the same identifying field for the first row.
		const identifierColumn = csvHeader[0];
		expect(identifierColumn).toBeTruthy();
		const csvIdentifier = csvRows[0][0];
		const jsonIdentifier = jsonRows[0][identifierColumn];
		expect(csvIdentifier).toBeTruthy();
		expect(String(jsonIdentifier)).toBe(csvIdentifier);
	});
});
